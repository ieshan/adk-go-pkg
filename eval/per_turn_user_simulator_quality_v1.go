package eval

import (
	"context"
	"fmt"
	"regexp"
	"strings"

	"google.golang.org/adk/v2/model"
	"google.golang.org/genai"
)

// isValidRegex matches the "is_valid" field in the LLM response, tolerating
// optional array brackets, quotes, whitespace, and trailing punctuation.
var isValidRegex = regexp.MustCompile(`"is_valid":\s*\[*[\n\s]*"*([^"\]]*)"*[\n\s]*\]*\s*[,\n\}]`)

// invalidLabels is the set of labels that count as an invalid user response.
var invalidLabels = map[string]bool{
	"invalid":         true,
	"almost":          true,
	"false":           true,
	"partially_valid": true,
	"partially valid": true,
	"partially":       true,
}

// validLabels is the set of labels that count as a valid user response.
var validLabels = map[string]bool{
	"valid": true,
	"true":  true,
}

// PerTurnUserSimulatorQualityV1Evaluator evaluates the quality of user
// messages generated by a user simulator against a conversation scenario.
//
// The first turn is checked for an exact match against the scenario's
// StartingPrompt. Subsequent turns are judged by an LLM. A final stop-signal
// turn verifies the conversation ended correctly.
type PerTurnUserSimulatorQualityV1Evaluator struct {
	*LlmAsJudgeEvaluator
	promptTemplate string
	stopSignal     string
}

// NewPerTurnUserSimulatorQualityV1Evaluator creates a new evaluator.
func NewPerTurnUserSimulatorQualityV1Evaluator(evalMetric EvalMetric, llm model.LLM) (*PerTurnUserSimulatorQualityV1Evaluator, error) {
	criterion := getLlmBackedUserSimulatorCriterion(evalMetric)

	base := NewLlmAsJudgeEvaluator(evalMetric, criterion.LlmAsAJudgeCriterion, llm, false)

	stopSignal := criterion.StopSignal
	if stopSignal == "" {
		stopSignal = "</finished>"
	}

	e := &PerTurnUserSimulatorQualityV1Evaluator{
		LlmAsJudgeEvaluator: base,
		promptTemplate:      PerTurnUserSimulatorQualityPrompt,
		stopSignal:          stopSignal,
	}

	base.ConvertAutoRaterResponseToScore = e.parseResponse
	base.AggregatePerInvocationSamplesFunc = e.aggregateSamples

	return e, nil
}

// EvaluateInvocations overrides the base implementation to implement the
// per-turn evaluation flow: first-turn exact match, intermediate LLM-judged
// turns, and a stop-signal turn.
func (e *PerTurnUserSimulatorQualityV1Evaluator) EvaluateInvocations(
	ctx context.Context,
	actualInvocations []Invocation,
	expectedInvocations []Invocation,
	conversationScenario *ConversationScenario,
) (*EvaluationResult, error) {
	if conversationScenario == nil {
		return nil, fmt.Errorf("conversation_scenario is needed by this metric")
	}
	if len(actualInvocations) == 0 {
		return &EvaluationResult{}, nil
	}

	// First turn: exact match against starting prompt.
	results := []PerInvocationResult{
		e.evaluateFirstTurn(actualInvocations[0], conversationScenario),
	}

	// Intermediate turns: LLM judge.
	for i := 1; i < len(actualInvocations); i++ {
		result, err := e.evaluateIntermediateTurn(ctx, actualInvocations[i], actualInvocations[:i], conversationScenario)
		if err != nil {
			return nil, fmt.Errorf("intermediate turn %d failed: %w", i, err)
		}
		results = append(results, result)
	}

	// Stop-signal turn: verify the conversation ended correctly.
	stopResult, err := e.evaluateStopSignalTurn(ctx, actualInvocations, conversationScenario)
	if err != nil {
		return nil, fmt.Errorf("stop signal turn failed: %w", err)
	}
	// If the conversation did not end correctly, mark the last user turn as failed.
	if stopResult.EvalStatus == EvalStatusFailed {
		results[len(results)-1] = stopResult
	}

	result := e.aggregateConversationResults(results)
	return &result, nil
}

// evaluateFirstTurn checks if the first user message matches the starting prompt.
func (e *PerTurnUserSimulatorQualityV1Evaluator) evaluateFirstTurn(
	firstInvocation Invocation,
	scenario *ConversationScenario,
) PerInvocationResult {
	if firstInvocation.UserContent == nil {
		return PerInvocationResult{
			ActualInvocation: firstInvocation,
			EvalStatus:       EvalStatusNotEvaluated,
		}
	}
	score := 0.0
	if strings.TrimSpace(GetTextFromContent(firstInvocation.UserContent)) ==
		strings.TrimSpace(scenario.StartingPrompt) {
		score = 1.0
	}
	return PerInvocationResult{
		ActualInvocation: firstInvocation,
		Score:            &score,
		EvalStatus:       GetEvalStatus(&score, e.evalMetric.Threshold),
	}
}

// evaluateIntermediateTurn uses the LLM to judge a single intermediate turn.
func (e *PerTurnUserSimulatorQualityV1Evaluator) evaluateIntermediateTurn(
	ctx context.Context,
	invocation Invocation,
	previousInvocations []Invocation,
	scenario *ConversationScenario,
) (PerInvocationResult, error) {
	prompt := e.formatLLMPrompt(invocation, previousInvocations, scenario)

	numSamples := e.criterion.JudgeModelOptions.NumSamples
	if numSamples <= 0 {
		numSamples = 5
	}

	var samples []PerInvocationResult
	for s := 0; s < numSamples; s++ {
		score, err := e.callAutoRater(ctx, prompt)
		if err != nil {
			return PerInvocationResult{}, fmt.Errorf("auto-rater call %d failed: %w", s, err)
		}
		result := PerInvocationResult{
			ActualInvocation: invocation,
			Score:            score.Score,
		}
		if score.Score != nil {
			result.EvalStatus = GetEvalStatus(score.Score, e.evalMetric.Threshold)
		} else {
			result.EvalStatus = EvalStatusNotEvaluated
		}
		samples = append(samples, result)
	}

	if len(samples) == 0 {
		return PerInvocationResult{
			ActualInvocation: invocation,
			EvalStatus:       EvalStatusNotEvaluated,
		}, nil
	}
	return e.aggregateSamples(samples), nil
}

// evaluateStopSignalTurn evaluates whether the conversation ended correctly
// by sending a proxy invocation containing the stop signal.
func (e *PerTurnUserSimulatorQualityV1Evaluator) evaluateStopSignalTurn(
	ctx context.Context,
	invocationHistory []Invocation,
	scenario *ConversationScenario,
) (PerInvocationResult, error) {
	stopInvocation := Invocation{
		InvocationID: "stop_signal_proxy_invocation",
		UserContent: &genai.Content{
			Parts: []*genai.Part{{Text: e.stopSignal}},
			Role:  "user",
		},
	}
	return e.evaluateIntermediateTurn(ctx, stopInvocation, invocationHistory, scenario)
}

// formatLLMPrompt builds the prompt for the LLM judge.
func (e *PerTurnUserSimulatorQualityV1Evaluator) formatLLMPrompt(
	invocation Invocation,
	previousInvocations []Invocation,
	scenario *ConversationScenario,
) string {
	plan := scenario.ConversationPlan
	history := formatConversationHistory(previousInvocations)
	generatedResponse := GetTextFromContent(invocation.UserContent)

	prompt := strings.ReplaceAll(e.promptTemplate, "{conversation_plan}", plan)
	prompt = strings.ReplaceAll(prompt, "{conversation_history}", history)
	prompt = strings.ReplaceAll(prompt, "{generated_user_response}", generatedResponse)
	prompt = strings.ReplaceAll(prompt, "{stop_signal}", e.stopSignal)
	return prompt
}

// parseResponse parses the LLM response for the "is_valid" field.
func (e *PerTurnUserSimulatorQualityV1Evaluator) parseResponse(resp *model.LLMResponse) AutoRaterScore {
	text := GetTextFromContent(resp.Content)
	if text == "" {
		return AutoRaterScore{}
	}

	label := parseIsValidLabel(text)
	switch label {
	case LabelValid:
		score := 1.0
		return AutoRaterScore{Score: &score}
	case LabelInvalid:
		score := 0.0
		return AutoRaterScore{Score: &score}
	default:
		return AutoRaterScore{}
	}
}

// parseIsValidLabel extracts the is_valid label from the LLM response text.
func parseIsValidLabel(response string) Label {
	match := isValidRegex.FindStringSubmatch(response)
	if match == nil {
		return LabelNotFound
	}
	label := strings.TrimSpace(strings.ReplaceAll(strings.Trim(match[1], "}"), ",", ""))
	label = strings.ToLower(label)
	if invalidLabels[label] {
		return LabelInvalid
	}
	if validLabels[label] {
		return LabelValid
	}
	return LabelNotFound
}

// aggregateSamples aggregates samples by majority vote.
func (e *PerTurnUserSimulatorQualityV1Evaluator) aggregateSamples(samples []PerInvocationResult) PerInvocationResult {
	if len(samples) == 0 {
		return PerInvocationResult{}
	}
	var positive, negative []PerInvocationResult
	for _, s := range samples {
		if s.Score == nil {
			continue
		}
		if *s.Score == 1.0 {
			positive = append(positive, s)
		} else {
			negative = append(negative, s)
		}
	}
	if len(positive) > len(negative) && len(positive) > 0 {
		return positive[0]
	}
	if len(negative) > 0 {
		return negative[0]
	}
	return samples[0]
}

// aggregateConversationResults computes the fraction of turns that passed.
func (e *PerTurnUserSimulatorQualityV1Evaluator) aggregateConversationResults(perInvocation []PerInvocationResult) EvaluationResult {
	numValid := 0.0
	numEvaluated := 0
	for _, r := range perInvocation {
		if r.EvalStatus == EvalStatusPassed && r.Score != nil {
			numValid += *r.Score
		}
		numEvaluated++
	}

	if numEvaluated == 0 {
		return EvaluationResult{PerInvocationResults: perInvocation}
	}

	overallScore := numValid / float64(numEvaluated)
	return EvaluationResult{
		OverallScore:         &overallScore,
		OverallEvalStatus:    GetEvalStatus(&overallScore, e.evalMetric.Threshold),
		PerInvocationResults: perInvocation,
	}
}

// formatConversationHistory builds a conversation history string from
// invocations, matching the Python _format_conversation_history format.
func formatConversationHistory(invocations []Invocation) string {
	var lines []string
	for _, inv := range invocations {
		if inv.UserContent != nil && len(inv.UserContent.Parts) > 0 {
			lines = append(lines, fmt.Sprintf("user: %s", GetTextFromContent(inv.UserContent)))
		}
		if inv.FinalResponse != nil {
			role := inv.FinalResponse.Role
			if role == "" {
				role = "model"
			}
			lines = append(lines, fmt.Sprintf("%s: %s", role, GetTextFromContent(inv.FinalResponse)))
		}
	}
	return strings.Join(lines, "\n\n")
}

// getLlmBackedUserSimulatorCriterion extracts the criterion from EvalMetric.
func getLlmBackedUserSimulatorCriterion(evalMetric EvalMetric) LlmBackedUserSimulatorCriterion {
	if evalMetric.Criterion != nil {
		if c, ok := evalMetric.Criterion.(*LlmBackedUserSimulatorCriterion); ok {
			return *c
		}
	}
	return LlmBackedUserSimulatorCriterion{
		LlmAsAJudgeCriterion: LlmAsAJudgeCriterion{
			JudgeModelOptions: DefaultJudgeModelOptions(),
		},
	}
}
